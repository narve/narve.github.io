/**
 * Eleventy config.
 *
 * The notable bit is the custom `.html` extension: it lets us treat each
 * `.html` post as a complete, raw-openable HTML document while still feeding
 * its content + metadata through the normal Eleventy layout pipeline.
 *
 *   - Metadata (title, date, tags, description) is read from native HTML
 *     elements: <title>, <meta name="description">, <meta property="article:*">,
 *     <time datetime="…">. No YAML front matter inside HTML files.
 *   - Only the inner HTML of CONTENT_SELECTOR (default "#blog-content") is
 *     used as the post body. Everything else in the source file is treated as
 *     standalone-only chrome and dropped at build time.
 *
 * Markdown posts are unaffected — they go through Eleventy's default
 * markdown-it pipeline with standard `---` YAML front matter.
 *
 * Adding a new <meta> → front-matter mapping: edit `extractMetadata` below,
 * then surface the field in `src/_includes/layouts/post.njk` if needed, and
 * document it in README.md.
 */

const fs = require("node:fs/promises");
const htmlParser = require("node-html-parser");
const rssPlugin = require("@11ty/eleventy-plugin-rss");

// CSS selector for the "real" article body within a standalone HTML post.
// Anything outside this element exists only for direct-file viewing.
const CONTENT_SELECTOR = "#blog-content";

function getAttr(node, name) {
  return node ? node.getAttribute(name) : undefined;
}

function readMeta(root, selector) {
  return getAttr(root.querySelector(selector), "content");
}

function readMetaAll(root, selector) {
  return root
    .querySelectorAll(selector)
    .map((n) => n.getAttribute("content"))
    .filter(Boolean);
}

// Maps standard HTML metadata elements to Eleventy front-matter keys.
function extractMetadata(root) {
  const data = {};
  const title = root.querySelector("title");
  if (title) data.title = title.text.trim();

  const description = readMeta(root, 'meta[name="description"]');
  if (description) data.description = description;

  // Prefer OpenGraph/Article published_time; fall back to first <time datetime>.
  const date =
    readMeta(root, 'meta[property="article:published_time"]') ||
    getAttr(root.querySelector("time[datetime]"), "datetime");
  if (date) data.date = date;

  // Repeatable <meta property="article:tag"> entries become a tag array.
  const tags = readMetaAll(root, 'meta[property="article:tag"]');
  if (tags.length) data.tags = tags;

  return data;
}

function extractContent(root) {
  const node =
    root.querySelector(CONTENT_SELECTOR) || root.querySelector("body");
  return node ? node.innerHTML : root.toString();
}

module.exports = function (eleventyConfig) {
  eleventyConfig.addPlugin(rssPlugin);
  eleventyConfig.addPassthroughCopy({ "src/assets": "assets" });

  // Take over .html handling so standalone HTML files can be posts.
  // See file header for the design.
  eleventyConfig.addExtension("html", {
    read: true,
    getData: true,
    async getData(inputPath) {
      const raw = await fs.readFile(inputPath, "utf8");
      const root = htmlParser.parse(raw);
      const data = extractMetadata(root);
      if (!data.layout) data.layout = "layouts/post.njk";
      return data;
    },
    compile(inputContent) {
      const root = htmlParser.parse(inputContent);
      const body = extractContent(root);
      return () => body;
    },
  });

  // Sorted set of every tag actually used by a post. Powers /tags/ and the
  // per-tag pages generated by src/tag.njk (which paginates over this list).
  // Excludes the synthetic "posts" tag added via posts.11tydata.js.
  eleventyConfig.addCollection("tagList", (api) => {
    const set = new Set();
    api.getAll().forEach((item) => {
      (item.data.tags || [])
        .filter((t) => t && t !== "posts")
        .forEach((t) => set.add(t));
    });
    return [...set].sort();
  });

  // For use inside post.njk: hide "posts" / "all" from the displayed tag list.
  eleventyConfig.addFilter("filterTagList", (tags) =>
    (tags || []).filter((t) => t && t !== "posts" && t !== "all")
  );

  eleventyConfig.addFilter("readableDate", (d) => {
    if (!d) return "";
    const date = d instanceof Date ? d : new Date(d);
    return date.toISOString().slice(0, 10);
  });

  eleventyConfig.addFilter("htmlDateString", (d) => {
    if (!d) return "";
    const date = d instanceof Date ? d : new Date(d);
    return date.toISOString();
  });

  return {
    dir: {
      input: "src",
      includes: "_includes",
      data: "_data",
      output: "_site",
    },
    markdownTemplateEngine: "njk",
    dataTemplateEngine: "njk",
  };
};
